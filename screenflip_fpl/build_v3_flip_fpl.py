#!/usr/bin/env python3
"""Build the Screen Flip boot-bin payload for SIGMA fp L 3.02.

    python3 -B screenflip_fpl/build_v3_flip_fpl.py \\
        --fpl .../FPL_V302/MAIN.bin \\
        --out /absolute/new/directory

The menu recipe reconstructs the tested row from the external fp L donor.
The task polls the registered variable; settings are card-local. The output
is a boot-bin component, not the merged card-root fpSup.BIN.
"""
import argparse
import hashlib
import json
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FPSUP = HERE.parent
ROOT = FPSUP
NATIVE = HERE / 'native'
CORE = FPSUP / 'screenflip' / 'core'
sys.path.insert(0, str(FPSUP / 'uishare'))
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(HERE))

from armasm import assemble, symbols                      # noqa: E402
import elf_text                                           # noqa: E402
import build_section                                      # noqa: E402
import menu                                               # noqa: E402

NAME = '4xFLIP.BIN'
SUP_ID = 'FLIP'
VERSION = 1
EXPERIMENT = ''                 # e.g. 'FPL_EXPERIMENT_A' (see flip_fpl.c)
UNITS = ['flip_core.c', 'profile.c', 'flip_fpl.c', 'ui_pool.c', 'ui_apply.c']
ENTRIES = {'OFF_INIT': 'fpl_card_init', 'OFF_TASK': 'fpl_task', 'OFF_CHANGED': 'fpl_changed'}
PUBLIC = re.compile(r'^(?!typedef\b|static\b|extern\b|#|enum\b|union\b|struct\s+\w+\s*\{)'
                    r'((?:USED\s+)?(?:const\s+)?(?:struct\s+\w+|u?int\w*_t|void|uintptr_t)'
                    r'\s*\**\s*(?:fpf|uis|uia|fpl|fplflip)_\w+\s*\()', re.M)
ENTRY_CALLS = {0xC001D740, 0xC001D7F0, 0xC000E91C, 0xC000EABC}
FPL_SITES = {0xC05E1D38: 0x3FFFF1B1, 0xC05E23A8: 0x428A6942, 0xC05E23C0: 0x69406902}


class BuildError(RuntimeError):
    pass


def unity(tree):
    """Copies with every public fpf_/uis_/uia_/fpl_/fplflip_ function internal
    (no .text relocation: the strict extractor refuses one), one unit
    including them, each module's private names prefixed (the uishare rule)."""
    uishare = FPSUP / 'uishare'
    for src in list(NATIVE.glob('*.[ch]')) + list(CORE.glob('*.[ch]')) + \
            list(uishare.glob('*.[ch]')):
        if 'fixture' in src.name:
            continue
        (tree / src.name).write_text(PUBLIC.sub(r'static \1', src.read_text()))
    lines = ['/* generated by screenflip_fpl/build_v3_flip_fpl.py */']
    for unit in UNITS:
        text = (tree / unit).read_text()
        private = sorted({n for n in re.findall(r'^static\s[^(=;]*?\b(\w+)\s*\(', text, re.M)
                          if not n.startswith(('fpf_', 'uis_', 'uia_', 'fpl_', 'fplflip_'))})
        macros = sorted(set(re.findall(r'^\s*#\s*define\s+(\w+)', text, re.M)))
        lines += [f'#define {n} {pathlib.Path(unit).stem}__{n}' for n in private]
        lines.append(f'#include "{tree / unit}"')
        lines += [f'#undef {n}' for n in private] + [f'#undef {m}' for m in macros]
    out = tree / 'unity.c'
    out.write_text('\n'.join(lines) + '\n')
    return out


def compile_unit(tree, settings_off, extra=''):
    unit = tree / 'unity.c'
    if extra:
        unit = tree / 'probe.c'
        unit.write_text((tree / 'unity.c').read_text() + extra)
    obj = tree / (unit.stem + '.o')
    clang = shutil.which('clang') or 'clang'
    cflags = list(build_section.CFLAGS)
    if EXPERIMENT:
        cflags += [f'-D{EXPERIMENT}']
    r = subprocess.run([clang] + cflags +
                       [f'-DFPF_SETTINGS_OFF=0x{settings_off:X}u',
                        '-DUIS_FPL_302', '-DUIA_FPL_302',
                        '-c', '-I', str(tree), str(unit), '-o', str(obj)],
                       capture_output=True, text=True)
    if r.returncode:
        raise BuildError('compile failed:\n' + r.stderr)
    return obj


def symbol_sizes(obj, prefix):
    d = obj.read_bytes()
    shoff, = struct.unpack_from('<I', d, 0x20)
    shentsize, shnum, _ = struct.unpack_from('<HHH', d, 0x2E)
    secs = [struct.unpack_from('<IIIIIIIIII', d, shoff + i * shentsize) for i in range(shnum)]
    symtab = next(x for x in secs if x[1] == 2)
    strtab = secs[symtab[6]]
    got = {}
    for i in range(symtab[5] // 16):
        n, _v, size, _info, _o, _s = struct.unpack_from('<IIIBBH', d, symtab[4] + 16 * i)
        name = d[strtab[4] + n:d.index(b'\0', strtab[4] + n)].decode()
        if name.startswith(prefix):
            got[name[len(prefix):]] = size
    return got


def check_entry(code):
    """entry_fpl.S: every absolute address it builds is a routine it may call
    (the allocator and the cache publishes); no direct bl out of the block."""
    from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM
    md = Cs(CS_ARCH_ARM, CS_MODE_ARM)
    lo = {}
    for i in md.disasm(code, 0):
        if i.mnemonic == 'bl':
            raise BuildError(f'entry_fpl.S has a direct bl at {i.address:#x}')
        if i.mnemonic in ('movw', 'movt'):
            reg, imm = i.op_str.split(', #')
            imm = int(imm, 0)
            if i.mnemonic == 'movw':
                lo[reg] = imm
            else:
                full = lo.pop(reg, 0) | imm << 16
                if full >= 0x30000000 and full not in ENTRY_CALLS:
                    raise BuildError(f'entry_fpl.S names 0x{full:08X}')


def check_stock(fpl_image):
    """The card will journal the three fp L string sites as stock sections;
    prove their live-fingerprinted stock words against the image here."""
    for a, s in FPL_SITES.items():
        stock = struct.unpack_from('<I', fpl_image, a - 0xC0000000)[0]
        if stock != s:
            raise BuildError(f'0x{a:08X}: stock 0x{stock:08X} != 0x{s:08X}')


def menu_block(image):
    block, info = menu.build(image)
    from ui import fpui
    _, ops, _ = fpui.decode(block)
    if any(code in (fpui.OP_HOOK_FV, fpui.OP_FILE) for code, _ in ops):
        raise BuildError('the row would hook the file redirect: claim it first')
    return block, info


def build_blob(fpl_main):
    """The blob (the file after its header) and the facts a test needs.

    The target and the stock UI resources are verified before compilation."""
    fpl_image = menu.image(fpl_main)
    block, row = menu_block(fpl_image)
    check_stock(fpl_image)
    src = NATIVE / 'entry_fpl.S'
    probe_defs = ['STATE_OFF=0x8', 'UI_OFF=0x8', 'UI_LEN=0x8', 'TOTAL=0x8'] + \
                 [f'{k}=0x1' for k in ENTRIES]
    first = symbols(src, probe_defs)
    c_base, settings_off = first['c_base'], first['settings']
    with tempfile.TemporaryDirectory(prefix='fplflip-v3-') as t:
        tree = pathlib.Path(t)
        unity(tree)
        text = elf_text.load_text(compile_unit(tree, settings_off))
        fields = ['ui_at', 'ui_len', 'task_entry', 'changed_entry', 'magic', 'base',
                  'self_path', 'name', 'result', 'task_id', 'page', 'row_y',
                  'registered', 'subscribe_result', 'ui_result', 'ui_op', 'first_id',
                   'install', 'install_polls', 'app_word', 'gate',
                   'desc_word', 'last_value', 'exp_ops']
        extra = '\nchar fpl_size_state[sizeof(struct fpl_card)];\n' + ''.join(
            f'char fpl_off_{f}[__builtin_offsetof(struct fpl_card, {f}) + 1];\n' for f in fields)
        sizes = symbol_sizes(compile_unit(tree, settings_off, extra), 'fpl_')
    layout = {f: sizes[f'off_{f}'] - 1 for f in fields}
    if [layout[f] for f in ('ui_at', 'ui_len', 'task_entry', 'changed_entry')] != [0, 4, 8, 12]:
        raise BuildError('entry_fpl.S fills state+0..+12; the struct moved them')
    for k, fn in ENTRIES.items():
        if not text.functions.get(fn, 0) & 1:
            raise BuildError(f'{fn} missing or not Thumb')
    ui_off = (c_base + len(text.code) + 7) & ~7
    blob_len = (ui_off + len(block) + 7) & ~7
    state_off = (blob_len + 63) & ~63
    block_bytes = (state_off + sizes['size_state'] + 0xFFF) & ~0xFFF
    defines = [f'STATE_OFF=0x{state_off:X}', f'UI_OFF=0x{ui_off:X}', f'UI_LEN=0x{len(block):X}',
               f'TOTAL=0x{block_bytes:X}'] + \
              [f'{k}=0x{text.functions[v]:X}' for k, v in ENTRIES.items()]
    code = assemble(src, defines)
    syms = symbols(src, defines)
    if syms['c_base'] != c_base or len(code) != c_base or syms['settings'] != settings_off:
        raise BuildError('entry_fpl.S moved between passes')
    check_entry(code[:syms['g_state']])
    blob = code + text.code
    blob += b'\0' * (ui_off - len(blob)) + block
    blob += b'\0' * (block_bytes - len(blob))   # through the zeroed state
    return blob, {'c_base': c_base, 'c_text': len(text.code), 'ui_off': ui_off,
                  'ui_len': len(block), 'blob_len': blob_len,
                  'payload_bytes': block_bytes,
                  'state_off': state_off,
                  'state_bytes': sizes['size_state'], 'block_bytes': block_bytes,
                  'settings_off': settings_off, 'row': row, 'defines': defines,
                  'layout': layout, 'symbols': {k: syms[k] for k in
                                                 ('entry', 'task_shim', 'changed_shim',
                                                  'g_state', 'w_task', 'w_changed',
                                                  'settings', 'c_base')},
                  'functions': {k: v for k, v in text.functions.items()
                                if k.startswith(('fpl_', 'fplflip_'))}}


def payload(fpl_main):
    """The VBIN boot-bin payload: the blob, zero-padded through the state,
    with its layout facts.  The card builder places it as a boot-bin whose
    entry is at offset 0."""
    return build_blob(fpl_main)


def main(argv=None):
    global EXPERIMENT
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--fpl', type=pathlib.Path, required=True,
                    help='official fp L 3.02 MAIN.bin')
    ap.add_argument('--out', type=pathlib.Path, required=True, help='new directory')
    ap.add_argument('--row-bench', action='store_true',
                    help='run a one-shot off-screen full-frame benchmark after startup')
    a = ap.parse_args(argv)
    if a.row_bench:
        EXPERIMENT = 'FPL_ROW_BENCH'
    out = a.out.resolve()
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f'{out} is not empty: this never overwrites a build')
    out.mkdir(parents=True, exist_ok=True)
    data, facts = payload(a.fpl)
    (out / NAME).write_bytes(data)
    sources = [pathlib.Path(__file__), *sorted(NATIVE.glob('*')),
               *sorted(CORE.glob('*.[ch]')),
               *sorted(p for p in (FPSUP / 'uishare').glob('*.[chS]') if 'fixture' not in p.name),
               HERE / 'menu.py', HERE / 'menu_recipe.json', FPSUP / 'uishare/ui/fpui.py',
               FPSUP / 'uishare/build_section.py', *sorted((ROOT/'tools').glob('*.py'))]
    (out / 'build.json').write_text(json.dumps({
        'product': 'fpScreenFlip for fp L 3.02, Loader v3 sup', 'file': NAME,
        'sup_id': SUP_ID, 'version': VERSION, 'experiment': EXPERIMENT,
        'fpl_sha256': hashlib.sha256(a.fpl.read_bytes()).hexdigest(),
        'blob': {k: v for k, v in facts.items() if k not in ('row', 'defines', 'layout',
                                                             'symbols', 'functions')},
        'layout': facts['layout'], 'row': facts['row'],
        'sha256': hashlib.sha256(data).hexdigest(),
        'sources': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in sources if p.is_file()},
        'written_to_card': False, 'camera_tested': False}, indent=1) + '\n')
    print(f'built into {out}')
    print(json.dumps({k: facts[k] for k in ('c_text', 'ui_len', 'blob_len', 'state_off',
                                            'state_bytes', 'block_bytes', 'settings_off')}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
